export const travellersService = {
  getTravellers() {
    try {
      const stored = localStorage.getItem(STORAGE_KEY_TRAVELLERS)
      if (stored) {
        return JSON.parse(stored)
      }
    } catch {
      // Fallback
    }
    localStorage.setItem(STORAGE_KEY_TRAVELLERS, JSON.stringify(DEFAULT_TRAVELLERS))
    return DEFAULT_TRAVELLERS
  },

  getTravellerById(id) {
    const list = this.getTravellers()
    return list.find((t) => t.id === id) || null
  },

  createTraveller(data) {
    const list = this.getTravellers()
    const nextNum = list.length + 8801
    const newTraveller = {
      id: `TRV-${nextNum}`,
      name: data.name,
      avatar: (data.name || 'TR')
        .split(' ')
        .map((w) => w[0])
        .join('')
        .slice(0, 2)
        .toUpperCase(),
      email: data.email || 'traveler@example.com',
      phone: data.phone || '+91 98000 00000',
      country: data.country || 'India',
      passport: data.passport || 'P0000000',
      expiry: data.expiry || '2030-01-01',
      status: data.status || 'ACTIVE',
      regDate: new Date().toISOString().split('T')[0],
      associatedCustomer: data.customer || data.name,
      company: data.company || 'Individual',
      totalVisaApps: 0,
      totalBookings: 0,
      visaApplications: [],
      holidayBookings: [],
    }
    const updated = [newTraveller, ...list]
    localStorage.setItem(STORAGE_KEY_TRAVELLERS, JSON.stringify(updated))
    return newTraveller
  },

  updateTraveller(id, updates) {
    const list = this.getTravellers()
    const updated = list.map((t) => (t.id === id ? { ...t, ...updates } : t))
    localStorage.setItem(STORAGE_KEY_TRAVELLERS, JSON.stringify(updated))
    return updated.find((t) => t.id === id)
  },

  toggleStatus(id) {
    const list = this.getTravellers()
    const updated = list.map((t) => {
      if (t.id === id) {
        return {
          ...t,
          status: t.status === 'ACTIVE' ? 'BLOCKED' : 'ACTIVE',
        }
      }
      return t
    })
    localStorage.setItem(STORAGE_KEY_TRAVELLERS, JSON.stringify(updated))
    return updated.find((t) => t.id === id)
  },

  deleteTraveller(id) {
    const list = this.getTravellers()
    const updated = list.filter((t) => t.id !== id)
    localStorage.setItem(STORAGE_KEY_TRAVELLERS, JSON.stringify(updated))
    return true
  },

  updateVisaStage(travellerId, visaId, newStage, newNotes) {
    const list = this.getTravellers()
    const updated = list.map((t) => {
      if (t.id === travellerId) {
        const apps = (t.visaApplications || []).map((app) => {
          if (app.id === visaId) {
            return {
              ...app,
              stage: newStage,
              status: newStage,
              notes: newNotes !== undefined ? newNotes : app.notes,
            }
          }
          return app
        })
        return { ...t, visaApplications: apps }
      }
      return t
    })
    localStorage.setItem(STORAGE_KEY_TRAVELLERS, JSON.stringify(updated))
    return true
  },

  updateHolidayStage(travellerId, bookingId, newStage, newNotes) {
    const list = this.getTravellers()
    const updated = list.map((t) => {
      if (t.id === travellerId) {
        const bks = (t.holidayBookings || []).map((b) => {
          if (b.id === bookingId) {
            return {
              ...b,
              stage: newStage,
              status: newStage,
              notes: newNotes !== undefined ? newNotes : b.notes,
            }
          }
          return b
        })
        return { ...t, holidayBookings: bks }
      }
      return t
    })
    localStorage.setItem(STORAGE_KEY_TRAVELLERS, JSON.stringify(updated))
    return true
  },

  updateVisaPayment(travellerId, visaId, paymentData) {
    const list = this.getTravellers()
    const updated = list.map((t) => {
      if (t.id === travellerId) {
        const apps = (t.visaApplications || []).map((app) => {
          if (app.id === visaId) {
            return {
              ...app,
              paidAmount: paymentData.newPaidTotal,
              paymentStatus: paymentData.newPaymentStatus,
              txnId: paymentData.referenceNo,
            }
          }
          return app
        })
        return { ...t, visaApplications: apps }
      }
      return t
    })
    localStorage.setItem(STORAGE_KEY_TRAVELLERS, JSON.stringify(updated))
    return true
  },

  updateHolidayPayment(travellerId, bookingId, paymentData) {
    const list = this.getTravellers()
    const updated = list.map((t) => {
      if (t.id === travellerId) {
        const bks = (t.holidayBookings || []).map((b) => {
          if (b.id === bookingId) {
            return {
              ...b,
              paidAmount: paymentData.newPaidTotal,
              paymentStatus: paymentData.newPaymentStatus,
              invoiceRef: paymentData.referenceNo,
            }
          }
          return b
        })
        return { ...t, holidayBookings: bks }
      }
      return t
    })
    localStorage.setItem(STORAGE_KEY_TRAVELLERS, JSON.stringify(updated))
    return true
  },
}

export default travellersService
