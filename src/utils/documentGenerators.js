/**
 * Document Generator Utilities
 * Handles generating and downloading PDF-like documents for visa/holiday cases.
 * Uses Blob-based text file generation as a lightweight alternative.
 */

/**
 * Download Application Dossier - creates a summary document of the case
 */
export const downloadApplicationDossier = (caseItem, type = 'visa') => {
  const isVisa = type === 'visa' || caseItem?.applicationType === 'VISA' || Boolean(caseItem?.visaType)
  const title = isVisa ? 'VISA APPLICATION DOSSIER' : 'HOLIDAY BOOKING APPLICATION'
  const applicantName = caseItem.applicant || caseItem.applicantName || caseItem.customer || 'Applicant'
  const amount = caseItem.amount !== undefined ? caseItem.amount : caseItem.price !== undefined ? caseItem.price : 0
  const officer = caseItem.officer || caseItem.assignedOfficer || 'Amit Verma (CO-101)'
  const officerId = caseItem.officerId || 'CO-101'
  const visaType = caseItem.visaType || caseItem.serviceRequired || 'Visitor Visa'
  const country = caseItem.country || caseItem.destination || 'N/A'
  const appliedDate = caseItem.appliedDate || caseItem.applicationDate || caseItem.bookingDate || 'N/A'
  const departureDate = caseItem.departureDate || caseItem.travelDate || 'N/A'
  const passport = caseItem.passport || 'N/A'
  const passportExp = caseItem.passportExp || caseItem.expiry || 'N/A'
  const phone = caseItem.phone || 'N/A'
  const email = caseItem.email || 'N/A'
  const paymentType = caseItem.paymentType || 'Prepaid'
  const paymentStatus = caseItem.paymentStatus || (caseItem.paidAmount >= amount ? 'COMPLETED' : 'PENDING')
  const stage = caseItem.stage || caseItem.status || 'UNDER_REVIEW'
  const docStatus = caseItem.docStatus || 'VERIFIED'
  const packageName = caseItem.packageName || caseItem.serviceRequired || `${country} Tour`
  const destination = caseItem.destination || caseItem.country || 'N/A'
  const duration = caseItem.duration || '5D / 4N'

  const content = `
═══════════════════════════════════════════════════════════
                    ${title}
═══════════════════════════════════════════════════════════

Case Reference:     ${caseItem.id}
Generated On:       ${new Date().toLocaleDateString('en-IN', { dateStyle: 'full' })}

─────────────────────────────────────────────────────────
  APPLICANT / CUSTOMER DETAILS
─────────────────────────────────────────────────────────

Name:               ${applicantName}
Phone:              ${phone}
Email:              ${email}
${isVisa ? `Passport:           ${passport}
Passport Expiry:    ${passportExp}` : `Departure Date:     ${departureDate}`}

─────────────────────────────────────────────────────────
  ${isVisa ? 'VISA' : 'BOOKING'} DETAILS
─────────────────────────────────────────────────────────

${isVisa ? `Destination:        ${country}
Visa Type:          ${visaType}
Document Status:    ${docStatus}` : `Package:            ${packageName}
Destination:        ${destination}
Duration:           ${duration}`}
Current Stage:      ${stage}
Assigned Officer:   ${officer} (${officerId})
Applied Date:       ${appliedDate}

─────────────────────────────────────────────────────────
  FINANCIAL SUMMARY
─────────────────────────────────────────────────────────

Total ${isVisa ? 'Fee' : 'Price'}:          ₹${Number(amount || 0).toLocaleString('en-IN')}
Paid Amount:        ₹${Number(caseItem.paidAmount || 0).toLocaleString('en-IN')}
Balance Due:        ₹${Math.max(0, Number(amount || 0) - Number(caseItem.paidAmount || 0)).toLocaleString('en-IN')}
Payment Type:       ${paymentType}
Payment Status:     ${paymentStatus}
Transaction Ref:    ${caseItem.txnId || caseItem.invoiceRef || 'N/A'}

═══════════════════════════════════════════════════════════
  This document is auto-generated by RH CRM System.
  For queries, contact the assigned case officer.
═══════════════════════════════════════════════════════════
`

  const blob = new Blob([content], { type: 'text/plain' })
  const url = URL.createObjectURL(blob)
  const link = document.createElement('a')
  link.href = url
  link.download = `${caseItem.id}_Application_Dossier.txt`
  document.body.appendChild(link)
  link.click()
  document.body.removeChild(link)
  URL.revokeObjectURL(url)
}

/**
 * Download Invoice - creates a financial invoice for the case
 */
